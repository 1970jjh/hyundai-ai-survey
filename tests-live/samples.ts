import { readFileSync, existsSync } from "node:fs";

/** .env.test.local 에서 테스트 키를 읽는다(값은 절대 출력하지 않음) */
export function loadTestKey(): string {
  if (process.env.GEMINI_API_KEY_FOR_TESTS) return process.env.GEMINI_API_KEY_FOR_TESTS;
  if (!existsSync(".env.test.local")) throw new Error(".env.test.local 이 없습니다.");
  const m = readFileSync(".env.test.local", "utf8").match(/^GEMINI_API_KEY_FOR_TESTS=(.+)$/m);
  if (!m) throw new Error("GEMINI_API_KEY_FOR_TESTS 가 없습니다.");
  return m[1].trim().replace(/^["']|["']$/g, "");
}

